import type { EveProjectLayout, EveProjectSummary } from "./source.js";

/**
 * Projection of eve's own post-build artifact `.eve/discovery/agent-discovery-manifest.json`
 * onto the platform summary shape. Once a Release has been built, this manifest -- not
 * Eveland's pre-install static file scan -- is the authority on what the agent contains:
 * it is produced by `eve info` from the same installed tree `eve build` compiled, so it cannot
 * drift from eve's layout rules the way re-derived heuristics can.
 *
 * Fail closed to null: this projection replaces the static entity lists wholesale, so
 * a manifest with an unknown schema version or missing entity arrays must not become
 * "authoritative emptiness". The caller keeps the static summary instead. The
 * agent-observer compatibility matrix runs this projection on manifests generated live
 * by every pinned eve binary, so a schema bump fails the matrix, not production.
 */
export type DiscoverySummaryProjection = {
  summarySource: "build-manifest";
  manifestVersion: number;
  agentId: string | null;
  layout: EveProjectLayout;
  diagnostics: { errors: number; warnings: number } | null;
  hooks: string[];
  channels: string[];
  subagentIds: string[];
  // `agents` (the root agent config module) and `capabilities.eveChat` stay
  // owned by the static scan: the manifest neither lists the root config
  // module nor exposes what an authored channel module exports.
} & Omit<EveProjectSummary, "agents">;

const MANIFEST_KIND = "eve-agent-discovery-manifest";

/**
 * Verified against the manifests generated by every Eve compatibility line.
 * 1.0.0-rc.3 and later emit v16, which keeps every entity but lists an agent's
 * authored sources in one `sources` array, in slot order, whose kind is the
 * first segment of each logical path (`tools/...` is a tool, `sandbox.ts` the
 * sandbox), instead of one array per kind; an Extension mount's manifest moved
 * the same way. 1.0.0-rc.1 and rc.2 emit v15 (as did 0.50.x through 0.91.x --
 * 0.83 retired on
 * 2026-11-04, 0.58
 * on 2026-09-23, when 0.63 and 0.64 were skipped; 0.65 was skipped on
 * 2026-09-24, 0.66 retired on 2026-09-26, 0.67 on 2026-09-29, and 0.62 on
 * 2026-10-02, 0.69 the same day, 0.70 on 2026-10-07, 0.72 and 0.73 on
 * 2026-10-08, 0.68 on 2026-10-09, 0.75 on 2026-10-10, 0.74 on 2026-10-14,
 * 0.76 on 2026-10-21, 0.79 on 2026-10-27, and 0.81 on 2026-11-02;
 * 0.69's through 0.75's discovery modules are byte-identical to 0.68's, 0.76.0
 * only adds an optional `deferred` flag to skill-package source refs, which the
 * projection does not read, and 0.79.0's are byte-identical to 0.76.0's, as
 * 0.81.1's are to 0.79.0's; 0.83.3's manifest module is byte-identical to
 * 0.81.1's, and its discovery only stops rejecting non-module files under
 * `lib/` and accepts one more Extension re-export form; 1.0.0-rc.1 keeps v15 and
 * only renames skill-package refs' `markdown` to `content`, which the
 * projection does not read). 0.62.0 stopped writing the optional
 * `instrumentation` module reference without bumping the version; the
 * projection never read it. v14 (0.45.0 only) left with the 0.45 line on
 * 2026-09-02, v13 with the 0.44 line before it.
 */
export const SUPPORTED_DISCOVERY_MANIFEST_VERSIONS: readonly number[] = [15, 16];

/** The first discovery manifest version that lists sources in one `sources` array. */
const SOURCES_LIST_VERSION = 16;

const SOURCE_KINDS = [
  "instructions",
  "tools",
  "skills",
  "connections",
  "schedules",
  "hooks",
  "channels",
] as const;

type SourceKind = (typeof SOURCE_KINDS)[number];
type Entry = { logicalPath: string };
type EntityLists = Record<SourceKind, Entry[]> & { sandbox: Entry | null };

/**
 * The slot a v16 source sits in, by the first segment of its logical path,
 * mirroring eve's `sourceKindOf` (`system` is the legacy instructions root;
 * `memory` is a slot the projection does not read). A file at the agent root
 * counts by its name without the extension: `sandbox.ts` is the sandbox,
 * `instructions.md` the instructions.
 */
const SOURCE_KIND_BY_SLOT_ROOT: Readonly<Record<string, SourceKind | "sandbox" | "memory">> = {
  channels: "channels",
  connections: "connections",
  hooks: "hooks",
  instructions: "instructions",
  memory: "memory",
  sandbox: "sandbox",
  schedules: "schedules",
  skills: "skills",
  system: "instructions",
  tools: "tools",
};

function slotOf(logicalPath: string): SourceKind | "sandbox" | "memory" | undefined {
  const first = logicalPath.split("/", 1)[0]!;
  const root = first.includes(".") ? first.slice(0, first.indexOf(".")) : first;
  return Object.hasOwn(SOURCE_KIND_BY_SLOT_ROOT, root) ? SOURCE_KIND_BY_SLOT_ROOT[root] : undefined;
}

/**
 * The per-kind entity lists of a manifest of either shape, or null when they
 * are missing or malformed. Every list must be present as an actual array of
 * well-formed entries, and the sandbox must be the documented null-or-entry
 * shape (at most one sandbox source on v16). A manifest missing them -- or
 * carrying elements without a logicalPath, or a v16 source outside every slot
 * -- is not "empty", it is unrecognized: silently dropping a corrupt element
 * would still overwrite the static entity lists with authoritative-looking
 * data.
 */
function readEntityLists(manifest: Record<string, unknown>, version: number): EntityLists | null {
  if (version >= SOURCES_LIST_VERSION) {
    const sources = manifest.sources;
    if (!Array.isArray(sources) || !sources.every(isEntry)) return null;
    const lists: EntityLists = {
      instructions: [],
      tools: [],
      skills: [],
      connections: [],
      schedules: [],
      hooks: [],
      channels: [],
      sandbox: null,
    };
    for (const source of sources) {
      const slot = slotOf(source.logicalPath);
      if (slot === undefined) return null;
      if (slot === "memory") continue;
      if (slot === "sandbox") {
        if (lists.sandbox !== null) return null;
        lists.sandbox = source;
        continue;
      }
      lists[slot].push(source);
    }
    return lists;
  }
  for (const key of SOURCE_KINDS) {
    const value = manifest[key];
    if (!Array.isArray(value) || !value.every(isEntry)) return null;
  }
  if (manifest.sandbox !== null && !isEntry(manifest.sandbox)) return null;
  return {
    instructions: manifest.instructions as Entry[],
    tools: manifest.tools as Entry[],
    skills: manifest.skills as Entry[],
    connections: manifest.connections as Entry[],
    schedules: manifest.schedules as Entry[],
    hooks: manifest.hooks as Entry[],
    channels: manifest.channels as Entry[],
    sandbox: manifest.sandbox as Entry | null,
  };
}

export function projectDiscoveryManifest(manifest: unknown): DiscoverySummaryProjection | null {
  if (!isRecord(manifest) || manifest.kind !== MANIFEST_KIND) return null;
  const version = manifest.version;
  if (typeof version !== "number" || !SUPPORTED_DISCOVERY_MANIFEST_VERSIONS.includes(version)) {
    return null;
  }
  const lists = readEntityLists(manifest, version);
  if (!lists) return null;
  if (!Array.isArray(manifest.subagents) || !manifest.subagents.every(isEntry)) return null;
  if (
    !Array.isArray(manifest.extensions) ||
    !manifest.extensions.every(isEntry) ||
    !Array.isArray(manifest.resolvedExtensions) ||
    !manifest.resolvedExtensions.every((mount) => isResolvedExtensionMount(mount, version))
  ) {
    return null;
  }

  const agentRoot = typeof manifest.agentRoot === "string" ? manifest.agentRoot : null;
  const appRoot = typeof manifest.appRoot === "string" ? manifest.appRoot : null;
  if (!agentRoot || !appRoot) return null;
  const layout: EveProjectLayout = agentRoot === appRoot ? "flat" : "nested";
  // Summary paths stay app-root-relative like the static scan's, so UI consumers
  // need no awareness of which producer wrote the summary.
  const root = layout === "nested" ? "agent/" : "";
  const prefix = (paths: string[]) => paths.map((entry) => `${root}${entry}`);

  const subagents = readEntries(manifest.subagents);
  const extensionContributions = readExtensionContributions(
    manifest.resolvedExtensions,
    root,
    version,
  );

  return {
    summarySource: "build-manifest",
    manifestVersion: version,
    agentId: typeof manifest.agentId === "string" ? manifest.agentId : null,
    layout,
    diagnostics: readDiagnostics(manifest.diagnosticsSummary),
    instructions: prefix(logicalPaths(lists.instructions)),
    tools: prefix(logicalPaths(lists.tools)),
    skills: prefix(logicalPaths(lists.skills)),
    subagents: [
      ...prefix(subagents.map((entry) => entry.logicalPath)),
      ...extensionContributions.subagents.map((entry) => entry.path),
    ],
    connections: prefix(logicalPaths(lists.connections)),
    schedules: [...prefix(logicalPaths(lists.schedules)), ...extensionContributions.schedules],
    sandbox: prefix(logicalPaths(lists.sandbox === null ? [] : [lists.sandbox])),
    hooks: prefix(logicalPaths(lists.hooks)),
    channels: prefix(logicalPaths(lists.channels)),
    subagentIds: [
      ...subagents
        .map((entry) => entry.subagentId)
        .filter((value): value is string => typeof value === "string"),
      ...extensionContributions.subagents.map((entry) => entry.id),
    ],
  };
}

type ExtensionManifestProjection = {
  agentRoot: string;
  schedules?: Array<{ logicalPath: string }>;
  sources?: Array<{ logicalPath: string }>;
  subagents: Array<{ logicalPath: string; subagentId?: unknown }>;
};

type ResolvedExtensionProjection = {
  namespace: string;
  manifest: ExtensionManifestProjection;
  overrides?: ExtensionManifestProjection;
};

function readExtensionContributions(
  value: unknown,
  root: string,
  version: number,
): { schedules: string[]; subagents: Array<{ id: string; path: string }> } {
  if (!Array.isArray(value)) return { schedules: [], subagents: [] };
  const schedules: string[] = [];
  const subagents: Array<{ id: string; path: string }> = [];
  const mounts = value
    .filter((mount): mount is ResolvedExtensionProjection =>
      isResolvedExtensionMount(mount, version),
    )
    .sort((left, right) => left.namespace.localeCompare(right.namespace));

  for (const mount of mounts) {
    const effectiveSchedules = mergeNamedEntries(
      mount.overrides ? extensionSchedules(mount.overrides, version) : [],
      extensionSchedules(mount.manifest, version),
      scheduleName,
    );
    schedules.push(
      ...effectiveSchedules.map(
        (entry) => `${root}extensions/${mount.namespace}/${entry.logicalPath}`,
      ),
    );

    const effectiveSubagents = mergeNamedEntries(
      mount.overrides?.subagents ?? [],
      mount.manifest.subagents,
      (entry) => (typeof entry.subagentId === "string" ? entry.subagentId : entry.logicalPath),
    );
    for (const entry of effectiveSubagents) {
      if (typeof entry.subagentId !== "string") continue;
      subagents.push({
        id: `${mount.namespace}__${entry.subagentId}`,
        path: `${root}extensions/${mount.namespace}/${entry.logicalPath}`,
      });
    }
  }
  return { schedules, subagents };
}

function mergeNamedEntries<T>(primary: T[], secondary: T[], name: (entry: T) => string): T[] {
  const names = new Set<string>();
  const merged: T[] = [];
  for (const entry of [...primary, ...secondary]) {
    const key = name(entry);
    if (names.has(key)) continue;
    names.add(key);
    merged.push(entry);
  }
  return merged;
}

function scheduleName(entry: { logicalPath: string }): string {
  const relative = entry.logicalPath.replace(/^schedules\//, "");
  return relative.replace(/\.(?:md|[cm]?[jt]s)$/, "");
}

/** A mount manifest's schedules: its `schedules` list (v15), or its schedule sources (v16). */
function extensionSchedules(
  manifest: ExtensionManifestProjection,
  version: number,
): Array<{ logicalPath: string }> {
  return version >= SOURCES_LIST_VERSION
    ? (manifest.sources ?? []).filter((source) => slotOf(source.logicalPath) === "schedules")
    : (manifest.schedules ?? []);
}

function isResolvedExtensionMount(
  value: unknown,
  version: number,
): value is ResolvedExtensionProjection {
  if (!isRecord(value) || typeof value.namespace !== "string" || !value.namespace) return false;
  if (!isExtensionManifest(value.manifest, version)) return false;
  return value.overrides === undefined || isExtensionManifest(value.overrides, version);
}

function isExtensionManifest(
  value: unknown,
  version: number,
): value is ExtensionManifestProjection {
  if (
    !isRecord(value) ||
    typeof value.agentRoot !== "string" ||
    !Array.isArray(value.subagents) ||
    !value.subagents.every(isEntry)
  ) {
    return false;
  }
  if (version >= SOURCES_LIST_VERSION) {
    return (
      Array.isArray(value.sources) &&
      value.sources.every(isEntry) &&
      value.sources
        .filter((source) => slotOf(source.logicalPath) === "schedules")
        .every(isSupportedExtensionScheduleEntry)
    );
  }
  return Array.isArray(value.schedules) && value.schedules.every(isSupportedExtensionScheduleEntry);
}

function isSupportedExtensionScheduleEntry(value: unknown): value is { logicalPath: string } {
  if (!isEntry(value)) return false;
  const normalized = value.logicalPath.replaceAll("\\", "/");
  if (!normalized.startsWith("schedules/")) return false;
  const relative = normalized.slice("schedules/".length);
  if (
    !relative ||
    relative.split("/").some((segment) => !segment || segment === "." || segment === "..")
  ) {
    return false;
  }
  return /\.(?:md|[cm]?[jt]s)$/.test(relative);
}

function isEntry(value: unknown): value is { logicalPath: string } {
  return isRecord(value) && typeof value.logicalPath === "string";
}

function readEntries(value: unknown): Array<{ logicalPath: string; subagentId?: unknown }> {
  if (!Array.isArray(value)) return [];
  return value.filter(
    (entry): entry is { logicalPath: string; subagentId?: unknown } =>
      isRecord(entry) && typeof entry.logicalPath === "string",
  );
}

function logicalPaths(value: unknown): string[] {
  return readEntries(Array.isArray(value) ? value : [value]).map((entry) => entry.logicalPath);
}

function readDiagnostics(value: unknown): { errors: number; warnings: number } | null {
  if (!isRecord(value) || typeof value.errors !== "number" || typeof value.warnings !== "number")
    return null;
  return { errors: value.errors, warnings: value.warnings };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
