import { access, cp, mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  buildGeneratedProviderSandboxModule,
  buildPlatformSandboxModule,
  buildSandboxShimModule,
  rewriteEveSandboxImports,
  SANDBOX_PLATFORM_DIR,
  SHIMMED_SANDBOX_ENTRY_POINTS,
  type ShimmedSandboxEntryPoint,
} from "./sandbox-provider-modules.js";

/** Where the built backend is vendored inside the release directory. */
export const VENDORED_BACKEND_DIR = ".eveland/sandbox-bwrap";

/** Extensions eve accepts for an authored module, highest resolution priority first. */
const AUTHORED_MODULE_EXTENSIONS = [".cts", ".mts", ".cjs", ".mjs", ".ts", ".js"] as const;

/**
 * First line of every module this file generates. `.js` is both an authored
 * module extension eve resolves and the extension we always write, so a
 * re-run must tell its own previous output apart from a project's authored
 * `sandbox.js` by content, not by path. Exported so `buildGeneratedSandboxModule`
 * and the removal loop can never drift apart.
 */
export const GENERATED_MODULE_MARKER = "// Generated by eveland at build time.";

/** Same-directory companion name used to preserve an authored definition's relative imports. */
const WRAPPED_MODULE_BASENAME = ".sandbox.eveland-authored";

export type SandboxInjectionInput = {
  releaseDir: string;
  /** Directory holding the built @evelandhq/sandbox-bwrap (its dist/). */
  backendDistDir: string;
};

/**
 * The sandbox shape a Release's Eve line compiles. Eve 0.64 replaced
 * object-form `defineSandbox({ backend })` with provider environments that
 * `eve build` prepares, and a module in one shape does not compile on the
 * other line.
 */
export type SandboxApi = "backend" | "provider";

/** The first Eve minor whose sandbox modules export provider environments. */
export const EVE_SANDBOX_PROVIDER_MINOR = 64;

export type SandboxInjectionResult = {
  api: SandboxApi;
  /** Paths (relative to releaseDir) of generated sandbox modules. */
  generated: string[];
  /** Backend shape: authored definitions whose lifecycle fields the generated wrapper retains. */
  wrapped: string[];
  /** Provider shape: authored modules kept in place with their eve sandbox imports redirected. */
  rewritten: string[];
  /** Paths (relative to releaseDir) of authored sandbox modules that were replaced. */
  replaced: string[];
};

/**
 * Chooses the sandbox shape from the Eve dependency the Release declares.
 * Injection runs before dependencies are installed, so the declaration is all
 * there is; the platform's version gate has already required it to resolve
 * inside one supported minor, and a declaration that does not name exactly
 * one minor is refused here too rather than guessed.
 */
export async function resolveSandboxApi(releaseDir: string): Promise<SandboxApi> {
  const packageJson = JSON.parse(await readFile(path.join(releaseDir, "package.json"), "utf8")) as {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  };
  const declared = packageJson.dependencies?.eve ?? packageJson.devDependencies?.eve ?? null;
  const minor = declared?.trim().match(/^[~^]?0\.(\d+)(?:\.(?:\d+|[x*]))?$/)?.[1];
  if (minor === undefined) {
    throw new Error(
      `Cannot choose the sandbox shape: the Release declares ${declared === null ? "no Eve dependency" : `Eve "${declared}"`}, which does not name a single Eve minor.`,
    );
  }
  return Number(minor) >= EVE_SANDBOX_PROVIDER_MINOR ? "provider" : "backend";
}

export function resolveSandboxRunTimeoutMs(env: NodeJS.ProcessEnv): string {
  const value = Number(env.EVELAND_SANDBOX_RUN_TIMEOUT_MS ?? 600_000);
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error("EVELAND_SANDBOX_RUN_TIMEOUT_MS must be a positive safe integer.");
  }
  return String(value);
}

function resolvePositiveSandboxInteger(
  env: NodeJS.ProcessEnv,
  name: string,
  fallback: number,
): string {
  const value = Number(env[name] ?? fallback);
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`${name} must be a positive safe integer.`);
  }
  return String(value);
}

export function resolveSandboxProcessLimits(env: NodeJS.ProcessEnv): {
  maxConcurrentProcesses: string;
  maxOutputBytes: string;
} {
  return {
    maxConcurrentProcesses: resolvePositiveSandboxInteger(
      env,
      "EVELAND_SANDBOX_MAX_CONCURRENT_PROCESSES",
      64,
    ),
    maxOutputBytes: resolvePositiveSandboxInteger(
      env,
      "EVELAND_SANDBOX_MAX_OUTPUT_BYTES",
      16 * 1024 * 1024,
    ),
  };
}

export function buildGeneratedSandboxModule(
  relativeImportPath: string,
  authoredImportPath?: string,
): string {
  const authoredImport = authoredImportPath
    ? `import authoredSandbox from ${JSON.stringify(authoredImportPath)};\n`
    : "";
  const authoredFields = authoredImportPath ? "  ...authoredSandbox,\n" : "";
  return `${GENERATED_MODULE_MARKER} Do not edit.
// The deploy host decides the sandbox backend; agent projects never declare one.
import { defineSandbox, defaultBackend } from "eve/sandbox";
import { bwrap, isBwrapAvailable } from "${relativeImportPath}";
${authoredImport}
const cacheDir = process.env.EVELAND_SANDBOX_CACHE_DIR;
const templateRevision = process.env.EVELAND_SANDBOX_TEMPLATE_REVISION;
const runTimeoutMs = Number(process.env.EVELAND_SANDBOX_RUN_TIMEOUT_MS ?? "600000");
const maxConcurrentProcesses = Number(process.env.EVELAND_SANDBOX_MAX_CONCURRENT_PROCESSES ?? "64");
const maxOutputBytes = Number(process.env.EVELAND_SANDBOX_MAX_OUTPUT_BYTES ?? "16777216");
const bwrapOptions = {
  ...(cacheDir ? { cacheDir } : {}),
  ...(templateRevision ? { templateRevision } : {}),
  runTimeoutMs,
  maxConcurrentProcesses,
  maxOutputBytes,
};

export default defineSandbox({
${authoredFields}  // Eveland owns only the backend. Authored lifecycle and metadata stay active.
  backend: () => (isBwrapAvailable() ? bwrap(bwrapOptions) : defaultBackend()),
});
`;
}

async function listDirectories(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);
}

async function pathKind(target: string): Promise<"file" | "directory" | "other" | null> {
  const entries = await readdir(path.dirname(target), { withFileTypes: true }).catch(() => []);
  const match = entries.find((entry) => entry.name === path.basename(target));
  if (!match) return null;
  if (match.isDirectory()) return "directory";
  if (match.isFile()) return "file";
  return "other";
}

async function removeAuthoredSandboxModules(
  moduleDir: string,
  relativeDir: string,
): Promise<string[]> {
  const removed: string[] = [];
  for (const extension of AUTHORED_MODULE_EXTENSIONS) {
    const authored = path.join(moduleDir, `sandbox${extension}`);
    const kind = await pathKind(authored);
    if (kind === "other") {
      await rm(authored, { force: true, recursive: true });
      removed.push(path.posix.join(relativeDir, `sandbox${extension}`));
      continue;
    }
    if (kind !== "file") continue;

    const contents = await readFile(authored, "utf8").catch(() => "");
    await rm(authored, { force: true });
    // `.js` is both an authored extension and what eveland generates. A re-run
    // must not report its own previous output as authored behavior it replaced.
    if (extension !== ".js" || !contents.startsWith(GENERATED_MODULE_MARKER)) {
      removed.push(path.posix.join(relativeDir, `sandbox${extension}`));
    }
  }
  return removed;
}

type WrappedAuthoredSandbox = {
  importPath?: string;
  replaced: string[];
  wrapped: string[];
};

/**
 * Moves the effective authored definition to a non-discoverable companion in
 * the same directory. Keeping it beside the original slot preserves all of
 * its relative imports; the generated sandbox.js imports and spreads it before
 * overriding only `backend`.
 */
async function wrapAuthoredSandboxModule(
  moduleDir: string,
  relativeDir: string,
): Promise<WrappedAuthoredSandbox> {
  type Candidate = {
    extension: (typeof AUTHORED_MODULE_EXTENSIONS)[number];
    path: string;
  };
  const authored: Candidate[] = [];
  const companions: Candidate[] = [];
  const replaced: string[] = [];
  let generatedModuleSeen = false;

  for (const extension of AUTHORED_MODULE_EXTENSIONS) {
    const modulePath = path.join(moduleDir, `sandbox${extension}`);
    const moduleKind = await pathKind(modulePath);
    if (moduleKind === "other") {
      await rm(modulePath, { force: true, recursive: true });
      replaced.push(path.posix.join(relativeDir, `sandbox${extension}`));
    } else if (moduleKind === "file") {
      const contents = await readFile(modulePath, "utf8").catch(() => "");
      if (extension === ".js" && contents.startsWith(GENERATED_MODULE_MARKER)) {
        generatedModuleSeen = true;
        await rm(modulePath, { force: true });
      } else {
        authored.push({ extension, path: modulePath });
      }
    }

    const companionPath = path.join(moduleDir, `${WRAPPED_MODULE_BASENAME}${extension}`);
    const companionKind = await pathKind(companionPath);
    if (companionKind === "file") {
      companions.push({ extension, path: companionPath });
    } else if (companionKind !== null) {
      throw new Error(
        `Cannot preserve authored sandbox in ${relativeDir}: reserved companion path collision at ${companionPath}.`,
      );
    }
  }

  if (companions.length > 1 || (companions.length === 1 && !generatedModuleSeen)) {
    throw new Error(
      `Cannot preserve authored sandbox in ${relativeDir}: reserved companion path collision for ${WRAPPED_MODULE_BASENAME}.`,
    );
  }
  if (companions.length === 1 && authored.length > 0) {
    throw new Error(
      `Cannot preserve authored sandbox in ${relativeDir}: both an authored module and an existing Eveland companion are present.`,
    );
  }

  let wrappedModule = companions[0];
  let wrappedLogicalPath: string | undefined;
  if (wrappedModule) {
    wrappedLogicalPath = path.posix.join(relativeDir, `sandbox${wrappedModule.extension}`);
  } else if (authored.length > 0) {
    const [effective, ...shadowed] = authored;
    wrappedModule = {
      extension: effective!.extension,
      path: path.join(moduleDir, `${WRAPPED_MODULE_BASENAME}${effective!.extension}`),
    };
    await rename(effective!.path, wrappedModule.path);
    wrappedLogicalPath = path.posix.join(relativeDir, `sandbox${effective!.extension}`);
    for (const extra of shadowed) {
      await rm(extra.path, { force: true });
      replaced.push(path.posix.join(relativeDir, `sandbox${extra.extension}`));
    }
  }

  return {
    ...(wrappedModule ? { importPath: `./${path.basename(wrappedModule.path)}` } : {}),
    replaced,
    wrapped: wrappedLogicalPath ? [wrappedLogicalPath] : [],
  };
}

/**
 * Every directory that owns a sandbox: the agent root plus every subagent,
 * however deeply nested.
 *
 * eve resolves subagents from `agent/subagents/<name>/` (confirmed against
 * eve 0.29.5's `discoverSubagents`, which defaults `subagentsDirectoryPath`
 * to `join(agentRoot, "subagents")`). `discoverLocalSubagentPackage` then
 * calls `discoverSandboxSource({ rootPath: subagentRoot })` *and*
 * `discoverSubagents({ agentRoot: subagentRoot })` for each directory-form
 * subagent it finds, so subagents can themselves declare further subagents
 * at `<subagentRoot>/subagents/<name>/`, arbitrarily deep — each level owns
 * its own sandbox slot. Only directory-form subagents own a sandbox (a
 * file-form subagent like `subagents/foo.ts` does not), so we only recurse
 * into directory children.
 */
async function collectSandboxRoots(
  releaseDir: string,
  root: string,
  roots: string[],
): Promise<void> {
  roots.push(root);
  const subagentsDir = path.join(releaseDir, root, "subagents");
  for (const name of await listDirectories(subagentsDir)) {
    await collectSandboxRoots(releaseDir, path.posix.join(root, "subagents", name), roots);
  }
}

export async function resolveSandboxRoots(releaseDir: string): Promise<string[]> {
  const agentDir = path.join(releaseDir, "agent");
  if ((await pathKind(agentDir)) !== "directory") return [];
  const roots: string[] = [];
  await collectSandboxRoots(releaseDir, "agent", roots);
  return roots;
}

export async function injectSandboxModules(
  input: SandboxInjectionInput,
): Promise<SandboxInjectionResult> {
  const api = await resolveSandboxApi(input.releaseDir);
  const roots = await resolveSandboxRoots(input.releaseDir);

  // Vendoring is a host-capability concern -- it must happen for every release
  // regardless of project layout, so `verifySandbox` (which imports the
  // vendored backend as a sibling module) always has something to import, even
  // when this project has no agent/ directory and therefore generates no
  // sandbox module below.
  const backendEntryPoint = path.join(input.backendDistDir, "index.js");
  const backendIsBuilt = await access(backendEntryPoint).then(
    () => true,
    () => false,
  );
  if (!backendIsBuilt) {
    throw new Error(
      `@evelandhq/sandbox-bwrap backend is unusable: ${input.backendDistDir} has no index.js. ` +
        "The package ships prebuilt, so this means an incomplete install. Run `pnpm install`, then retry.",
    );
  }
  if (
    api === "provider" &&
    (await pathKind(path.join(input.backendDistDir, "provider.js"))) === null
  ) {
    throw new Error(
      `@evelandhq/sandbox-bwrap at ${input.backendDistDir} has no provider.js, which Eve ` +
        `0.${EVE_SANDBOX_PROVIDER_MINOR} and later need. Install @evelandhq/sandbox-bwrap 0.4.0 or newer, then retry.`,
    );
  }

  const vendorDir = path.join(input.releaseDir, VENDORED_BACKEND_DIR);
  await rm(vendorDir, { force: true, recursive: true });
  await mkdir(path.dirname(vendorDir), { recursive: true });
  await cp(input.backendDistDir, vendorDir, { recursive: true });

  return api === "provider"
    ? await injectProviderModules(input.releaseDir, roots)
    : await injectBackendModules(input.releaseDir, roots);
}

async function injectBackendModules(
  releaseDir: string,
  roots: string[],
): Promise<SandboxInjectionResult> {
  const generated: string[] = [];
  const wrapped: string[] = [];
  const replaced: string[] = [];

  for (const root of roots) {
    const rootDir = path.join(releaseDir, root);
    let generatedRoot = root;
    let authoredImportPath: string | undefined;

    // eve resolves `sandbox/` before `sandbox.<ext>`. A real directory must
    // survive so its `workspace/**` seeds are compiled; generate the platform
    // backend inside that directory and wrap its authored definition.
    // A file or symlink named `sandbox` cannot safely carry workspace seeds,
    // so remove it and fall back to the flat generated-module shape.
    const sandboxDir = path.join(rootDir, "sandbox");
    const sandboxKind = await pathKind(sandboxDir);
    if (sandboxKind === "directory") {
      generatedRoot = path.posix.join(root, "sandbox");
      const authored = await wrapAuthoredSandboxModule(sandboxDir, generatedRoot);
      authoredImportPath = authored.importPath;
      wrapped.push(...authored.wrapped);
      replaced.push(...authored.replaced);
      // Eve's folder layout wins discovery, so a flat definition is shadowed
      // and cannot contribute lifecycle behavior.
      replaced.push(...(await removeAuthoredSandboxModules(rootDir, root)));
    } else if (sandboxKind !== null) {
      await rm(sandboxDir, { force: true, recursive: true });
      replaced.push(path.posix.join(root, "sandbox"));
      replaced.push(...(await removeAuthoredSandboxModules(rootDir, root)));
    } else {
      const authored = await wrapAuthoredSandboxModule(rootDir, root);
      authoredImportPath = authored.importPath;
      wrapped.push(...authored.wrapped);
      replaced.push(...authored.replaced);
    }

    const importPath = path.posix.join(
      path.posix.relative(generatedRoot, ""),
      VENDORED_BACKEND_DIR,
      "index.js",
    );
    await writeFile(
      path.join(releaseDir, generatedRoot, "sandbox.js"),
      buildGeneratedSandboxModule(importPath, authoredImportPath),
      "utf8",
    );
    generated.push(path.posix.join(generatedRoot, "sandbox.js"));
  }

  return { api: "backend", generated, wrapped, rewritten: [], replaced };
}

/**
 * The Eve >= 0.64 shape. Every slot ends up with exactly one module eve loads:
 * the authored one, kept in place with its eve sandbox imports redirected to
 * the platform shims, or a generated one when the project left the slot
 * empty. A kept module needs no companion file, because redirecting its
 * imports is enough to put its environment on the platform provider.
 */
async function injectProviderModules(
  releaseDir: string,
  roots: string[],
): Promise<SandboxInjectionResult> {
  const generated: string[] = [];
  const rewritten: string[] = [];
  const replaced: string[] = [];

  const platformDir = path.join(releaseDir, SANDBOX_PLATFORM_DIR);
  await rm(platformDir, { force: true, recursive: true });
  await mkdir(platformDir, { recursive: true });
  await writeFile(
    path.join(platformDir, "platform.js"),
    buildPlatformSandboxModule(GENERATED_MODULE_MARKER),
    "utf8",
  );
  for (const entryPoint of Object.keys(
    SHIMMED_SANDBOX_ENTRY_POINTS,
  ) as ShimmedSandboxEntryPoint[]) {
    await writeFile(
      path.join(platformDir, `${entryPoint}.js`),
      buildSandboxShimModule(entryPoint, GENERATED_MODULE_MARKER),
      "utf8",
    );
  }

  for (const root of roots) {
    const rootDir = path.join(releaseDir, root);
    let slot = root;
    const sandboxDir = path.join(rootDir, "sandbox");
    const sandboxKind = await pathKind(sandboxDir);
    if (sandboxKind === "directory") {
      // eve resolves `sandbox/` before `sandbox.<ext>`, and the directory
      // carries the workspace seeds, so the module lives inside it and a flat
      // module beside it is shadowed.
      slot = path.posix.join(root, "sandbox");
      replaced.push(...(await removeAuthoredSandboxModules(rootDir, root)));
    } else if (sandboxKind !== null) {
      await rm(sandboxDir, { force: true, recursive: true });
      replaced.push(path.posix.join(root, "sandbox"));
    }

    const slotDir = path.join(releaseDir, slot);
    const authored = await keepEffectiveAuthoredModule(slotDir, slot);
    replaced.push(...authored.replaced);
    const toPlatform = path.posix.relative(slot, SANDBOX_PLATFORM_DIR);
    if (authored.modulePath) {
      const source = await readFile(authored.modulePath, "utf8");
      const result = rewriteEveSandboxImports(
        source,
        (entryPoint) => `${toPlatform}/${entryPoint}.js`,
      );
      if (result.source !== source) await writeFile(authored.modulePath, result.source, "utf8");
      rewritten.push(path.posix.join(slot, path.basename(authored.modulePath)));
      continue;
    }
    await writeFile(
      path.join(slotDir, "sandbox.js"),
      buildGeneratedProviderSandboxModule(`${toPlatform}/platform.js`, GENERATED_MODULE_MARKER),
      "utf8",
    );
    generated.push(path.posix.join(slot, "sandbox.js"));
  }

  return { api: "provider", generated, wrapped: [], rewritten, replaced };
}

/**
 * Finds the authored module eve would load from one slot and removes the
 * rest: lower-priority duplicates it would shadow, anything that is not a
 * regular file, and this function's own earlier output.
 */
async function keepEffectiveAuthoredModule(
  slotDir: string,
  slot: string,
): Promise<{ modulePath?: string; replaced: string[] }> {
  const replaced: string[] = [];
  let modulePath: string | undefined;
  for (const extension of AUTHORED_MODULE_EXTENSIONS) {
    const candidate = path.join(slotDir, `sandbox${extension}`);
    const kind = await pathKind(candidate);
    if (kind === null) continue;
    const logicalPath = path.posix.join(slot, `sandbox${extension}`);
    if (kind !== "file") {
      await rm(candidate, { force: true, recursive: true });
      replaced.push(logicalPath);
      continue;
    }
    const contents = await readFile(candidate, "utf8").catch(() => "");
    const isOwnOutput = extension === ".js" && contents.startsWith(GENERATED_MODULE_MARKER);
    if (isOwnOutput || modulePath !== undefined) {
      await rm(candidate, { force: true });
      if (!isOwnOutput) replaced.push(logicalPath);
      continue;
    }
    modulePath = candidate;
  }
  return { ...(modulePath ? { modulePath } : {}), replaced };
}
