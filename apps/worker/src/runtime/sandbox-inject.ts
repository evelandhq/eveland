import { access, cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/** Where the built backend is vendored inside the release directory. */
export const VENDORED_BACKEND_DIR = ".eveland/sandbox-bwrap";

/** Extensions eve accepts for an authored module, highest resolution priority first. */
const AUTHORED_MODULE_EXTENSIONS = [".cts", ".mts", ".cjs", ".mjs", ".ts", ".js"] as const;

/**
 * First line of every module this file generates. `.js` is both an authored
 * module extension eve resolves and the extension we always write, so a
 * re-run must tell its own previous output apart from a project's authored
 * `sandbox.js` by content, not by path. Exported so `buildGeneratedSandboxModule`
 * and the removal loop can never drift apart.
 */
export const GENERATED_MODULE_MARKER = "// Generated by eveland at build time.";

export type SandboxInjectionInput = {
  releaseDir: string;
  /** Directory holding the built @eveland/sandbox-bwrap (its dist/). */
  backendDistDir: string;
};

export type SandboxInjectionResult = {
  /** Paths (relative to releaseDir) of generated sandbox modules. */
  generated: string[];
  /** Paths (relative to releaseDir) of authored sandbox modules that were replaced. */
  replaced: string[];
};

export function buildGeneratedSandboxModule(relativeImportPath: string): string {
  return `${GENERATED_MODULE_MARKER} Do not edit.
// The deploy host decides the sandbox backend; agent projects never declare one.
import { defineSandbox, defaultBackend } from "eve/sandbox";
import { bwrap, isBwrapAvailable } from "${relativeImportPath}";

const cacheDir = process.env.EVELAND_SANDBOX_CACHE_DIR;
const templateRevision = process.env.EVELAND_SANDBOX_TEMPLATE_REVISION;
const bwrapOptions = {
  ...(cacheDir ? { cacheDir } : {}),
  ...(templateRevision ? { templateRevision } : {}),
};

export default defineSandbox({
  backend: () => (isBwrapAvailable() ? bwrap(bwrapOptions) : defaultBackend()),
});
`;
}

async function listDirectories(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);
}

async function pathKind(target: string): Promise<"file" | "directory" | null> {
  const entries = await readdir(path.dirname(target), { withFileTypes: true }).catch(() => []);
  const match = entries.find((entry) => entry.name === path.basename(target));
  if (!match) return null;
  return match.isDirectory() ? "directory" : "file";
}

async function removeAuthoredSandboxModules(moduleDir: string, relativeDir: string): Promise<string[]> {
  const removed: string[] = [];
  for (const extension of AUTHORED_MODULE_EXTENSIONS) {
    const authored = path.join(moduleDir, `sandbox${extension}`);
    if ((await pathKind(authored)) !== "file") continue;

    const contents = await readFile(authored, "utf8").catch(() => "");
    await rm(authored, { force: true });
    // `.js` is both an authored extension and what eveland generates. A re-run
    // must not report its own previous output as authored behavior it replaced.
    if (extension !== ".js" || !contents.startsWith(GENERATED_MODULE_MARKER)) {
      removed.push(path.posix.join(relativeDir, `sandbox${extension}`));
    }
  }
  return removed;
}

/**
 * Every directory that owns a sandbox: the agent root plus every subagent,
 * however deeply nested.
 *
 * eve resolves subagents from `agent/subagents/<name>/` (confirmed against
 * eve 0.24.2's `discoverSubagents`, which defaults `subagentsDirectoryPath`
 * to `join(agentRoot, "subagents")`). `discoverLocalSubagentPackage` then
 * calls `discoverSandboxSource({ rootPath: subagentRoot })` *and*
 * `discoverSubagents({ agentRoot: subagentRoot })` for each directory-form
 * subagent it finds, so subagents can themselves declare further subagents
 * at `<subagentRoot>/subagents/<name>/`, arbitrarily deep — each level owns
 * its own sandbox slot. Only directory-form subagents own a sandbox (a
 * file-form subagent like `subagents/foo.ts` does not), so we only recurse
 * into directory children.
 */
async function collectSandboxRoots(releaseDir: string, root: string, roots: string[]): Promise<void> {
  roots.push(root);
  const subagentsDir = path.join(releaseDir, root, "subagents");
  for (const name of await listDirectories(subagentsDir)) {
    await collectSandboxRoots(releaseDir, path.posix.join(root, "subagents", name), roots);
  }
}

export async function resolveSandboxRoots(releaseDir: string): Promise<string[]> {
  const agentDir = path.join(releaseDir, "agent");
  if ((await pathKind(agentDir)) !== "directory") return [];
  const roots: string[] = [];
  await collectSandboxRoots(releaseDir, "agent", roots);
  return roots;
}

export async function injectSandboxModules(input: SandboxInjectionInput): Promise<SandboxInjectionResult> {
  const roots = await resolveSandboxRoots(input.releaseDir);
  const generated: string[] = [];
  const replaced: string[] = [];

  // Vendoring is a host-capability concern -- it must happen for every release
  // regardless of project layout, so `verifySandbox` (which imports the
  // vendored backend as a sibling module) always has something to import, even
  // when this project has no agent/ directory and therefore generates no
  // sandbox module below.
  const backendEntryPoint = path.join(input.backendDistDir, "index.js");
  const backendIsBuilt = await access(backendEntryPoint).then(
    () => true,
    () => false,
  );
  if (!backendIsBuilt) {
    throw new Error(
      `@eveland/sandbox-bwrap backend is not built: ${input.backendDistDir} has no index.js. ` +
        "Run `pnpm --filter @eveland/sandbox-bwrap build`, then retry.",
    );
  }

  const vendorDir = path.join(input.releaseDir, VENDORED_BACKEND_DIR);
  await rm(vendorDir, { force: true, recursive: true });
  await mkdir(path.dirname(vendorDir), { recursive: true });
  await cp(input.backendDistDir, vendorDir, { recursive: true });

  for (const root of roots) {
    const rootDir = path.join(input.releaseDir, root);
    let generatedRoot = root;

    // eve resolves `sandbox/` before `sandbox.<ext>`. A real directory must
    // survive so its `workspace/**` seeds are compiled; generate the platform
    // backend inside that directory and replace only its authored definition.
    // A file or symlink named `sandbox` cannot safely carry workspace seeds,
    // so remove it and fall back to the flat generated-module shape.
    const sandboxDir = path.join(rootDir, "sandbox");
    const sandboxKind = await pathKind(sandboxDir);
    if (sandboxKind === "directory") {
      generatedRoot = path.posix.join(root, "sandbox");
      replaced.push(...(await removeAuthoredSandboxModules(sandboxDir, generatedRoot)));
    } else if (sandboxKind !== null) {
      await rm(sandboxDir, { force: true, recursive: true });
      replaced.push(path.posix.join(root, "sandbox"));
    }
    replaced.push(...(await removeAuthoredSandboxModules(rootDir, root)));

    const importPath = path.posix.join(
      path.posix.relative(generatedRoot, ""),
      VENDORED_BACKEND_DIR,
      "index.js",
    );
    await writeFile(
      path.join(input.releaseDir, generatedRoot, "sandbox.js"),
      buildGeneratedSandboxModule(importPath),
      "utf8",
    );
    generated.push(path.posix.join(generatedRoot, "sandbox.js"));
  }

  return { generated, replaced };
}
